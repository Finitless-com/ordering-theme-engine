#!/usr/bin/env node
/**
 * Compiles the format's meta-schema (meta/theme-schema-1.json, JSON Schema
 * 2020-12) into a standalone validator, src/shape-validator.js, so that the
 * package checks a schema's shape with no runtime dependency: Ajv writes the
 * validator's code, and esbuild bundles into it the few Ajv runtime helpers
 * that code requires. src/shape.ts reads it; `pnpm build` copies it to dist/
 * and vitest's global setup writes it before the tests.
 *
 *   node scripts/build-shape-validator.mjs [out.js]
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const require = createRequire(resolve(ROOT, 'package.json'))
const Ajv2020 = require('ajv/dist/2020').default
const standalone = require('ajv/dist/standalone').default

/** The validator's module: `export default validate`, every import bundled in. */
export async function buildShapeValidator(out = resolve(ROOT, 'src/shape-validator.js')) {
  const meta = JSON.parse(readFileSync(resolve(ROOT, 'meta/theme-schema-1.json'), 'utf8'))
  // strict: false, as the meta-schema leaves some types implicit; the
  // checks are the same.
  const ajv = new Ajv2020({ allErrors: true, strict: false, code: { source: true, esm: true } })
  const source = standalone(ajv, ajv.compile(meta))
  const bundled = await build({
    stdin: { contents: source, resolveDir: ROOT, sourcefile: 'shape-validator.js' },
    bundle: true,
    format: 'esm',
    platform: 'neutral',
    minify: true,
    legalComments: 'inline',
    write: false,
  })
  const banner = '// Generated by scripts/build-shape-validator.mjs from meta/theme-schema-1.json. Do not edit.\n'
  writeFileSync(out, banner + bundled.outputFiles[0].text)
  return out
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)
if (isMain) {
  const out = await buildShapeValidator(process.argv[2] ? resolve(process.argv[2]) : undefined)
  console.log(`wrote ${out}`)
}
